-- 1. TABLA DE ACEITES IMPORTADOS Y VENTA POR PALLETS
CREATE TABLE IF NOT EXISTS public.pallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    brand TEXT NOT NULL,
    oil_type TEXT NOT NULL,
    viscosity TEXT NOT NULL,
    units_per_pallet INTEGER NOT NULL DEFAULT 48,
    pallet_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    unit_price_approx NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    image TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    origin TEXT NOT NULL DEFAULT 'Importado',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABLA DE PRODUCTOS INDIVIDUALES
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    brand TEXT NOT NULL,
    viscosity TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL CHECK(price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0),
    image TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA DE CLIENTES
CREATE TABLE IF NOT EXISTS public.clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT DEFAULT '',
    company TEXT DEFAULT '',
    address TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABLA DE PEDIDOS
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES public.clients(id) ON DELETE CASCADE,
    total NUMERIC(10, 2) NOT NULL CHECK(total >= 0),
    status TEXT NOT NULL DEFAULT 'Recibido',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA DE DETALLES DE PEDIDO
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK(quantity > 0),
    price NUMERIC(10, 2) NOT NULL CHECK(price >= 0)
);

-- 6. HABILITAR SEGURIDAD (RLS) Y PERMITIR LECTURA PÚBLICA (ANON)
ALTER TABLE public.pallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura pública para catálogo y pallets
CREATE POLICY "Lectura pública de pallets" ON public.pallets
    FOR SELECT USING (active = true);

CREATE POLICY "Lectura pública de productos" ON public.products
    FOR SELECT USING (true);

-- Políticas de inserción pública para pedidos desde el sitio web
CREATE POLICY "Permitir crear clientes anónimos" ON public.clients
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir crear pedidos anónimos" ON public.orders
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir crear items de pedidos anónimos" ON public.order_items
    FOR INSERT WITH CHECK (true);

